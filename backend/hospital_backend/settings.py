def _build_database_config() -> dict:
    """Use DIRECT_URL for schema/fixture commands, DATABASE_URL for runtime, or SQLite locally."""
    cmd = sys.argv[1] if len(sys.argv) > 1 else ''
    if cmd in _SESSION_COMMANDS:
        db_url = os.environ.get('DIRECT_URL') or os.environ.get('DATABASE_URL', '')
    else:
        db_url = os.environ.get('DATABASE_URL') or os.environ.get('DIRECT_URL', '')

    if not db_url:
        return {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
        }

    parsed = urlparse(db_url)
    query = parse_qs(parsed.query)
    is_pgbouncer = (
        query.get('pgbouncer', ['false'])[0].lower() == 'true'
        or parsed.port == 6543
    )
    default_ssl = 'require' if 'supabase' in (parsed.hostname or '') else 'prefer'
    sslmode = query.get('sslmode', [default_ssl])[0]

    config = {
        'ENGINE': 'django.db.backends.postgresql',
        'NAME': unquote(parsed.path.lstrip('/')) or 'postgres',
        'USER': unquote(parsed.username or ''),
        'PASSWORD': unquote(parsed.password or ''),
        'HOST': parsed.hostname or '',
        'PORT': str(parsed.port or 5432),
        # Reuse TLS connection across requests to avoid ~1.5s remote handshake per request
        'CONN_MAX_AGE': int(os.environ.get('DB_CONN_MAX_AGE', '300')),
        'CONN_HEALTH_CHECKS': True,
        'OPTIONS': {'sslmode': sslmode},
    }
    if is_pgbouncer:
        # Transaction-mode pooler (PgBouncer port 6543) does not support persistent server-side cursors
        config['DISABLE_SERVER_SIDE_CURSORS'] = True
    return config


